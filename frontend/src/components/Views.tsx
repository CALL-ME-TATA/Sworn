export function Steps({ r }: { r: Run }) {
  const at = progress(r);
  return (
    <ol className="steps" aria-label="Run progress">
      {STEPS.map(([name, what], i) => {
        const cls = i < at ? "done" : i === at ? (r.error ? "stop" : "now") : "";
        return (
          <li key={name} className={cls} aria-current={cls === "now" ? "step" : undefined}>
            {name}<small>{cls === "stop" ? "stopped here" : what}</small>
          </li>
        );
      })}
    </ol>
  );
}

function stoppedHelp(err: string) {
  if (/no working/.test(err)) return "Every hired agent for that role failed during the run, so there was nobody left to do the work. The usual cause is the AI provider being rate-limited. Wait a minute and run again; the Hiring tab shows which agent failed and why.";
  if (/no trustworthy/.test(err)) return "No candidate passed all three checks for that role. The Hiring tab shows why each one was turned away. Run again; trials are drawn at random.";
  return "The Hiring tab shows which agent failed and why. Wait a minute and run again.";
}

export function Answer({ r }: { r: Run }) {
  if (r.error) {
    return <div className="answer stopped"><div><p>{r.answer ?? r.error}</p><p className="help mt-3">{stoppedHelp(r.error)}</p></div></div>;
  }
  if (!r.answer) return <div className="answer waiting"><p>The answer appears here once the hired team has retrieved, read, reasoned and verified its claims.</p></div>;
  const byId = Object.fromEntries(r.claims.map((c) => [c.id, c]));
  const names = (list: (string | undefined)[]) => [...new Set(list.filter(Boolean))].join(", ") || "—";
  // "fact [c3]." reads as "fact. [c3]"
  const text = r.answer.replace(/\s*((?:\[c\d+\]\s*)+)([.,;:!?])/g, "$2 $1");
  const parts = text.split(/\s*\[(c\d+)\]/g);
  const task = r.tasks[0];
  return (
    <div className="answer">
      <p>
        {parts.map((p, i) => {
          if (i % 2 === 0) return p;
          const c = byId[p];
          const tip = c ? `“${c.quote}” — ${sourceName(c.source_url)} · reasoned by ${c.produced_by_name}, checked by ${c.verified_by_name}` : p;
          return <span key={i}> <a className="cite" href={`#evidence/${p}`} title={tip}>{p}</a></span>;
        })}
      </p>
      <dl className="credits">
        <div><dt>Planned by</dt><dd>{task?.planned_by_name ?? "—"}</dd></div>
        <div><dt>Retrieved by</dt><dd>{names(r.tasks.map((t) => t.retrieved_by_name))}</dd></div>
        <div><dt>Read by</dt><dd>{names(r.tasks.map((t) => t.read_by_name))}</dd></div>
        <div><dt>Reasoned by</dt><dd>{names(r.claims.map((c) => c.produced_by_name))}</dd></div>
        <div><dt>Checked by</dt><dd>{names(r.claims.map((c) => c.verified_by_name))}</dd></div>
        <div><dt>Generated by</dt><dd>{names([r.written_by_name])}</dd></div>
      </dl>
    </div>
  );
}

export function Scoreline({ r }: { r: Run }) {
  const m = r.metrics;
  const parts: [React.ReactNode, string][] = [
    [<><b>{m.claims_supported ?? 0}/{m.claims ?? 0}</b> claims supported</>, "Claims a second agent confirmed against their source page"],
    [<><b>{m.bad_agents_rejected ?? "-"}</b> bad agents out</>, "Our two deliberately bad agents (one lies, one is too slow) that were turned away"],
    [<><b>{m.third_party_passed ?? 0}/{m.third_party_tried ?? 0}</b> third-party passed</>, "Agents registered by other people that passed every check"],
    ...(m.failover_ms != null ? [[<><b>{(m.failover_ms / 1000).toFixed(2)} s</b> takeover</>, "Time for a backup to take over after an agent went offline"] as [React.ReactNode, string]] : []),
    [<><b>{m.feedback_written ?? "-"}</b> on-chain</>, "Agent scores written to the Solana Agent Registry"],
  ];
  return <p className="scoreline">{parts.map(([p, tip], i) => <span key={i} title={tip}>{p}</span>)}</p>;
}

export function ClarifyOptions({ c, question, asTyped = true, onRun }: { c: Extract<Clarify, { clear: false }>; question: string; asTyped?: boolean; onRun: (q: string) => void }) {
  return (
    <>
      <p className="m-0 mb-1 font-display text-[28px] leading-tight font-extrabold uppercase">{c.ask}</p>
      <p className="mb-4 text-ink-2">You asked: “{question}”</p>
      <div className="options mb-4 grid gap-2">
        {c.options.map((o) => (
          <button key={o.question} type="button" onClick={() => onRun(o.question)}>
            <b className="font-display text-[19px] leading-tight font-extrabold uppercase tracking-[.04em]">{o.label}</b>
            <span className="text-ink-2">{o.question}</span>
          </button>
        ))}
      </div>
      {asTyped && <button type="button" className="linkish" onClick={() => onRun(question)}>Run my question as typed</button>}
    </>
  );
}

/** After a run: suggestions appear on their own when nothing was found; otherwise on request. */
export function FollowUp({ r, onRun }: { r: Run; onRun: (q: string) => void }) {
  const found = r.claims.some((c) => c.status === "supported");
  const [state, setState] = useState<"idle" | "loading" | Clarify>(found ? "idle" : "loading");
  useEffect(() => {
    if (state === "loading") askClarify(r.question, true).then(setState);
  }, [state, r.question]);
  if (state === "idle") return <button type="button" className="linkish mt-4" onClick={() => setState("loading")}>Not what you meant? Get more specific follow-up questions</button>;
  return (
    <div className="clarify mt-6 mb-0 border-ink">
      {state === "loading" ? <p className="m-0 label-caps text-lg text-blue">Finding better questions to ask...</p>
        : state.clear ? <p className="m-0 text-ink-2">No better phrasing found. Try naming the exact event, person or article.</p>
        : <ClarifyOptions c={state} question={r.question} asTyped={false} onRun={onRun} />}
    </div>
  );
}

export function Evidence({ r, target }: { r: Run; target?: string }) {
  useEffect(() => {
    if (target) document.getElementById(target)?.scrollIntoView({ block: "center" });
  }, [target]);
  if (!r.claims.length) return <><H2>Evidence</H2><p className="empty-view">Claims appear here as the hired reasoner states them, each with its exact quote and source.</p></>;
  const used = new Set(citedIds(r.answer));
  return (
    <>
      <H2 note="Every claim with its exact quote, its source, the agents that found and stated it, and the different agent that checked it">Evidence</H2>
      <div className="overflow-x-auto">
        <table className="tbl">
          <thead><tr><th>ID</th><th>Claim and exact quote</th><th>Source</th><th>Reasoned by</th><th>Checked by</th><th>Verdict</th><th>Answer</th></tr></thead>
          <tbody>
            {r.tasks.map((t, gi) => {
              const rows = r.claims.filter((c) => c.sub_question === t.question);
              return [
                <tr key={t.id} className="group"><td colSpan={7}>
                  <small>Sub-question {gi + 1} of {r.tasks.length} · retrieved by {t.retrieved_by_name ?? "..."} · read by {t.read_by_name ?? "..."}</small>
                  {t.question}
                </td></tr>,
                ...rows.map((c) => (
                  <tr key={c.id} id={c.id} className={target === c.id ? "target" : ""}>
                    <td><span className="font-display text-xl font-extrabold">{c.id}</span></td>
                    <td>{c.text}{c.quote !== c.text && <span className="mt-1 block text-base text-ink-2">“{c.quote}”</span>}</td>
                    <td><a href={c.source_url} target="_blank" rel="noopener">{sourceName(c.source_url)}</a></td>
                    <td className="font-semibold whitespace-nowrap">{c.produced_by_name}</td>
                    <td className="font-semibold whitespace-nowrap">{c.verified_by_name ?? "..."}</td>
                    <td><span className={`verdict ${c.status === "supported" ? "ok" : c.status === "pending" ? "wait" : "no"}`} title={c.reason ?? "not checked yet"}>{c.status}</span></td>
                    <td>{!r.answer || r.error ? null : used.has(c.id)
                      ? <span className="label-caps text-[15px]">Cited</span>
                      : <span className="label-caps text-[15px] font-semibold text-ink-3" title={c.status === "supported" ? "Verified, but the generator did not need it" : "Not verified, so the generator could not use it"}>Not used</span>}</td>
                  </tr>
                )),
              ];
            })}
          </tbody>
        </table>
      </div>
    </>
  );
}

export function Record({ r }: { r: Run }) {
  if (!r.feedback.length) return <><H2>On-chain record</H2><p className="empty-view">When the run ends, every agent&apos;s score is written to the Solana Agent Registry and listed here with its transaction.</p></>;
  return (
    <>
      <H2 note="Each agent's score, written to the Solana Agent Registry by the orchestrator's wallet. Open any transaction to check it.">On-chain record</H2>
      <div className="overflow-x-auto">
        <table className="tbl">
          <thead><tr><th>Agent</th><th className="c-role">Role</th><th>Score</th><th>Outcome</th><th>Transaction</th></tr></thead>
          <tbody>
            {r.feedback.map((f) => (
              <tr key={`${f.asset}-${f.role}`}>
                <td className="font-semibold whitespace-nowrap">{f.name} <Asset asset={f.asset} /></td>
                <td className="c-role">{f.role}</td>
                <td><b>{f.score}</b></td>
                <td><span className={`verdict ${f.outcome === "passed" ? "ok" : "no"}`}>{f.outcome}</span></td>
                <td>{f.tx ? <a href={explorer("tx", f.tx)} target="_blank" rel="noopener">{f.tx.slice(0, 8)}…</a> : <span className="text-ink-3">{f.error ?? "not sent"}</span>}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="mt-4 max-w-[75ch] text-ink-2">
        Validation records (each claim, the agent that made it, the agent that checked it and the verdict) are stored in Postgres and
        served at <a href={`/api/runs/${r.run_id}/validations`} target="_blank" rel="noopener"><code>/api/runs/{r.run_id}/validations</code></a>.
        Every on-chain entry links back to this run&apos;s report.
      </p>
    </>
  );
}

function Band({ big, total, profile, callable, children, label }: { big: number; total: number; profile: number; callable: number; children: React.ReactNode; label: string }) {
  return (
    <div className="registry mt-6">
      <div className="big"><em>{big}</em> of {total.toLocaleString()}</div>
      <p>{children}</p>
      <div className="track" role="img" aria-label={label}>
        <span className="profile" style={{ width: `${(100 * profile) / total}%` }} />
        <span className="callable" style={{ width: `${(100 * callable) / total}%` }} />
      </div>
    </div>
  );
}

export function Registries({ r }: { r: Run }) {
  const g = r.registry;
  if (!g) return <><H2>The open registries</H2><p className="empty-view">Reading the registries...</p></>;
  const s = g.sati;
  return (
    <>
      <H2 note="Solana devnet, read at the start of this run">The open registries</H2>
      <Band big={g.with_endpoint} total={g.total} profile={g.with_profile} callable={g.with_endpoint} label={`${g.with_endpoint} of ${g.total} agents callable`}>
        <b>Solana Agent Registry (8004):</b> registered agents with an endpoint you can call at all ({((100 * g.with_endpoint) / g.total).toFixed(1)}%).{" "}
        {g.with_profile.toLocaleString()} have a readable profile and {g.with_skills} declare any skills.
      </Band>
      {s && (
        <Band big={s.with_endpoint} total={s.total} profile={s.with_profile} callable={s.with_endpoint} label={`${s.with_endpoint} of ${s.total} SATI agents list an endpoint`}>
          <b>SATI registry:</b> agents whose profile lists an MCP or A2A endpoint. {s.with_profile} of {s.total} profiles could be read.
          Most listed endpoints are template placeholders, so every candidate is screened before it is hired.
        </Band>
      )}
    </>
  );
}

export function Baseline({ compare }: { compare: Compare | null }) {
  if (!compare) return <><H2>Fixed team vs ours</H2><p className="empty-view">No comparison yet. Run <code>python -m app.baseline</code> to compare a fixed team with ours on the same questions.</p></>;
  const sum = (k: keyof Compare["rows"][number]) => compare.rows.reduce((n, x) => n + (x[k] as number), 0);
  const team = (label: string, used: number, bad: number, ours: boolean, how: string) => {
    const badPct = used ? Math.round((100 * bad) / used) : 0;
    return (
      <div className={`border-t-[6px] bg-sheet px-6 pt-4 pb-6 ${ours ? "border-blue" : "border-ink"}`}>
        <div className="flex items-baseline justify-between gap-4">
          <span className="font-display text-2xl font-extrabold uppercase tracking-[.04em]">{label}</span>
          <span className={`text-right font-display text-6xl leading-none font-extrabold ${ours ? "text-blue" : "text-red"}`}>
            {badPct}%<small className="label-caps mt-0.5 block text-[15px] text-ink-2">unsupported</small>
          </span>
        </div>
        <div className="my-4 flex h-[26px] bg-rule" role="img" aria-label={`${label}: ${bad} of ${used} claims unsupported`}>
          <span className={ours ? "bg-blue" : "bg-ink-3"} style={{ width: `${100 - badPct}%` }} />
          <span className="bg-red" style={{ width: `${badPct}%` }} />
        </div>
        <p className="m-0 text-ink-2">{used - bad} of {used} claims in its answers were backed by their source; <b className="text-ink">{bad} were not</b>. {how}</p>
      </div>
    );
  };
  return (
    <>
      <H2 note={`Same ${compare.rows.length} questions, same agents, same grading${compare.mode ? ` · ${compare.mode}` : ""}`}>Fixed team vs ours</H2>
      <p className="mb-4 max-w-[75ch] text-ink-2">A claim is <b>unsupported</b> when its quote cannot be found on the source page it cites. That is how invented facts get into an answer.</p>
      <div className="grid gap-8 md:grid-cols-2">
        {team("Fixed team", sum("baseline_used"), sum("baseline_unsupported"), false, "A hardcoded team with one bad agent, and no screening or checking.")}
        {team("Ours", sum("ours_used"), sum("ours_unsupported"), true, "Candidates screened before hiring, and every claim checked by a second agent.")}
      </div>
      <H2>Question by question</H2>
      <div className="overflow-x-auto">
        <table className="tbl">
          <thead><tr><th>Question</th><th>Fixed team</th><th>Ours</th></tr></thead>
          <tbody>
            {compare.rows.map((x) => (
              <tr key={x.question}>
                <td>{x.question}</td>
                <td className={x.baseline_unsupported ? "font-semibold text-red" : ""}>{x.baseline_unsupported} of {x.baseline_used} unsupported</td>
                <td className={x.ours_unsupported ? "font-semibold text-red" : ""}>{x.ours_unsupported} of {x.ours_used} unsupported</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </>
  );
}

/** Past runs from Postgres; picking one shows its full report. */
export function History({ current, onPick }: { current?: string; onPick: (id: string | null) => void }) {
  const [runs, setRuns] = useState<RunSummary[] | null>(null);
  useEffect(() => { getJson<RunSummary[]>("/api/runs?limit=30").then(setRuns); }, []);
  if (!runs) return <><H2>History</H2><p className="empty-view">Loading past runs...</p></>;
  return (
    <>
      <H2 note="Every run is stored in Postgres with its full report">History</H2>
      <div className="overflow-x-auto">
        <table className="tbl">
          <thead><tr><th>Question</th><th>When</th><th>Took</th><th>Claims supported</th><th /></tr></thead>
          <tbody>
            {runs.map((x) => (
              <tr key={x.id} className={x.id === current ? "target" : ""}>
                <td>{x.question}</td>
                <td className="whitespace-nowrap">{new Date(x.started_at).toLocaleString()}</td>
                <td>{x.finished_at ? `${seconds(x.started_at, x.finished_at)} s` : "running"}</td>
                <td>{x.error ? <span className="verdict no">stopped</span> : `${x.supported ?? 0}/${x.claims ?? 0}`}</td>
                <td><button type="button" className="linkish" onClick={() => onPick(x.id)}>Open</button></td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </>
  );
}
